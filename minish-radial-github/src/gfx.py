# Generates 4bpp GBA tiles for the radial menu using the game's fixed OBJ palettes.
# Palette 0 (cursor oranges), 3 (HUD button bubbles), 4 (warm stone greys).
import math, sys
from PIL import Image

PAL = {
 0: "40b088 701810 a02818 d04020 f85010 f8b848 f88810 f8b828 f8e038 f8f860 706060 988888 c0b0b0 e8d8d8 f8f8f8 000000",
 3: "30a078 7898a8 b8c8d8 d8e0f0 f8f8f8 f8f8f8 f800f8 f800f8 f800f8 f800f8 f800f8 f800f8 f800f8 f800f8 f8f8f8 000000",
 4: "40b088 785000 b88018 e8b820 f8e828 f8f890 704810 a07840 d0b088 f8e0b8 686858 909078 c0c0a8 e8e8d0 f8f8f8 000000",
}
PAL = {k: [tuple(int(c[i:i+2], 16) for i in (0, 2, 4)) for c in v.split()] for k, v in PAL.items()}

def disc(size, r, ramp, outline=15, inset=False):
    """Bevelled bubble. ramp = (shadow, body, light, highlight) palette indices."""
    shadow, body, light, hi = ramp
    c = size / 2
    img = [[0] * size for _ in range(size)]
    for y in range(size):
        for x in range(size):
            dx, dy = x + 0.5 - c, y + 0.5 - c
            d = math.hypot(dx, dy)
            if d > r + 0.35:
                continue
            if d > r - 0.85:
                img[y][x] = outline
                continue
            # light from top-left
            lit = (-dx - dy) / (math.sqrt(2) * max(d, 0.001))
            if d > r - 2.2:  # bevel ring
                if inset:
                    img[y][x] = shadow if lit > 0.15 else (light if lit < -0.35 else body)
                else:
                    img[y][x] = hi if lit > 0.35 else (shadow if lit < -0.25 else light)
            else:
                if inset:
                    # recessed: inner shadow on top-left edge
                    img[y][x] = shadow if (lit > 0.4 and d > r - 3.4) else body
                else:
                    # sheen in the upper-left of the body
                    sx, sy = dx + r * 0.35, dy + r * 0.35
                    img[y][x] = light if math.hypot(sx, sy) < r * 0.42 else body
    return img

def socket():
    # warm stone socket, recessed like the pause-menu slots
    return disc(32, 12.5, (11, 12, 13, 14), inset=True)

def hub():
    # big HUD-style bubble (palette 3: 1 dark, 2 body, 3 light, 4 white)
    return disc(32, 15.5, (1, 2, 3, 4))

B_GLYPH = [
    "1111.",
    "1...1",
    "1111.",
    "1...1",
    "1...1",
    "1111.",
]

def badge():
    img = disc(16, 7.5, (1, 2, 3, 4))
    for gy, row in enumerate(B_GLYPH):
        for gx, ch in enumerate(row):
            if ch == "1":
                img[5 + gy][5 + gx] = 15
    return img

CORNER = [
    "WWWWWWW.",
    "WYOOOOW.",
    "WOOOOOW.",
    "WOODWWW.",
    "WOOW....",
    "WOOW....",
    "WWWW....",
    "........",
]

def corner():
    m = {"W": 14, "O": 4, "Y": 8, "D": 3, ".": 0}
    return [[m[ch] for ch in row] for row in CORNER]

def to_tiles(img):
    h, w = len(img), len(img[0])
    out = []
    for ty in range(h // 8):
        for tx in range(w // 8):
            words = []
            for y in range(8):
                v = 0
                for x in range(8):
                    v |= (img[ty * 8 + y][tx * 8 + x] & 15) << (4 * x)
                words.append(v)
            out.extend(words)
    return out

def preview(parts, path, scale=6):
    W = sum(len(p[0][0]) for p in parts) + 8 * (len(parts) + 1)
    H = max(len(p[0]) for p in parts) + 16
    im = Image.new("RGB", (W, H), (40, 64, 56))
    x = 8
    for img, pal in parts:
        for y, row in enumerate(img):
            for xx, v in enumerate(row):
                if v:
                    im.putpixel((x + xx, 8 + y), PAL[pal][v])
        x += len(img[0]) + 8
    im.resize((W * scale, H * scale), Image.NEAREST).save(path)

if __name__ == "__main__":
    parts = [(socket(), 4), (hub(), 3), (badge(), 3), (corner(), 0)]
    preview(parts, sys.argv[2] if len(sys.argv) > 2 else "preview.png")
    tiles = []
    for img, _ in parts:
        tiles += to_tiles(img)
    with open(sys.argv[1], "w") as f:
        f.write("// generated by gfx.py\n")
        f.write("#define RADIAL_GFX_TILES %d\n" % (len(tiles) // 8))
        f.write("static const unsigned int sRadialGfx[] = {\n")
        for i in range(0, len(tiles), 8):
            f.write("    " + ", ".join("0x%08x" % t for t in tiles[i:i + 8]) + ",\n")
        f.write("};\n")
